const catalogs = { vi, en } as const;

export function tr(locale: TutorLocale | undefined, key: TutorMessageKey, params: Record<string, string | number> = {}): string {
  const template: string = catalogs[locale === "en" ? "en" : "vi"][key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (params[name] !== undefined ? String(params[name]) : ""));
}

export const tutorCatalogs = catalogs;

/** Explicit language switch commands from chat ("English", "EN", "Tiếng Việt", "VI"). */
export function detectLanguageCommand(text: string): TutorLocale | null {
  const t = text.trim().toLowerCase();
  if (/^(english|en|lang en|language en)$/.test(t)) return "en";
  if (/^(tiếng việt|tieng viet|vi|vn|lang vi|ngôn ngữ vi)$/.test(t)) return "vi";
  return null;
}
